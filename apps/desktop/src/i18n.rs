//! Trilingual UI strings (`en`, `ko`, `zh-CN`) aligned 1:1 with `apps/canvas/src/i18n/messages.ts`.

#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub enum UiLang {
    En,
    Ko,
    ZhCn,
}

impl UiLang {
    pub fn parse(raw: &str) -> Self {
        match raw.trim().to_ascii_lowercase().as_str() {
            "ko" | "ko-kr" => Self::Ko,
            "zh" | "zh-cn" | "zh-hans" => Self::ZhCn,
            _ => Self::En,
        }
    }

    pub fn next(self) -> Self {
        match self {
            Self::En => Self::Ko,
            Self::Ko => Self::ZhCn,
            Self::ZhCn => Self::En,
        }
    }

    pub fn display_name(self) -> &'static str {
        match self {
            Self::En => "English",
            Self::Ko => "한국어",
            Self::ZhCn => "简体中文",
        }
    }
}

